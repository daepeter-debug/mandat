import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {coverSources,ballotValue,readCoverVotes} from '../lib/magazine-cover.ts';
import {archive,parties,dataVerified} from '../lib/polls.ts';
import {politicalNews,newsChecked} from '../lib/political-news.ts';
import {aggregateAsPoll} from '../lib/aggregate.ts';
import {scenarioFromPoll} from '../lib/parliament.ts';
const raw=JSON.parse(readFileSync('public/data/hlasovania/index.json','utf8'));
const votes=readCoverVotes(raw);assert.ok(votes);assert.equal(votes.length,raw.hlasovania.length);
assert.equal(readCoverVotes({v:2,hlasovania:[]}),null);
assert.equal(readCoverVotes({v:1,hlasovania:[{...votes[0],za:-1}]}),null);
assert.equal(readCoverVotes({v:1,hlasovania:[{...votes[0],nepritomni:votes[0].nepritomni+1}]}),null);
assert.equal(readCoverVotes({v:1,hlasovania:[{...votes[0],id:NaN}]}),null);
const asOf=[dataVerified,newsChecked].sort().at(-1);
const cover=coverSources(archive,politicalNews,votes,asOf);
assert.deepEqual(cover,coverSources([...archive].reverse(),[...politicalNews].reverse(),[...votes].reverse(),asOf));
assert.ok(cover.poll.published<=asOf);assert.ok(cover.day.every(n=>n.published===cover.lead.published));
assert.equal(cover.lead.rank,Math.min(...cover.day.map(n=>n.rank??99)));
assert.equal(cover.vote.datum,votes.map(v=>v.datum).sort().at(-1));
assert.equal(coverSources([],[],[],'2026-10-10').latest,null);
assert.equal(coverSources([{...archive[0],published:null}],[],[],'2026-10-10').poll,null);
assert.equal(coverSources([{...archive[0],published:'2026-10-11'}],[],[],'2026-10-10').poll,null);
const news={...politicalNews[0],published:'2026-10-08'};
assert.equal(coverSources([{...archive[0],published:'2026-10-09'}],[news],[],'2026-10-10').latest,'poll');
assert.equal(coverSources([], [news], [{...votes[0],datum:'2026-10-10'}], '2026-10-10').latest,'vote');
assert.equal(coverSources([], [news], [{...votes[0],datum:'2026-10-11'}], '2026-10-10').latest,'news');
assert.equal(ballotValue(NaN),null);assert.equal(ballotValue(Infinity),null);assert.equal(ballotValue(-5),0);assert.equal(ballotValue(101),100);assert.equal(ballotValue(5.06),5.1);
const poll=aggregateAsPoll(),before=JSON.stringify(poll.values);
assert.equal(scenarioFromPoll(poll).rows.reduce((sum,p)=>sum+p.seats,0),150);
for(const p of parties){const value=ballotValue((poll.values[p.id]??0)+.5);assert.equal(value,Math.round(((poll.values[p.id]??0)+.5)*10)/10);}
assert.equal(JSON.stringify(poll.values),before);
console.log('Ballot/cover: presné publikácie, poradie správ, budúce/chýbajúce dátumy, platné súčty 150 hlasov a nezmenený model OK.');
