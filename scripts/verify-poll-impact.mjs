import assert from 'node:assert/strict';
import { pollImpact, agencyComparison } from '../lib/poll-impact.ts';
import { archive } from '../lib/polls.ts';
import { currentAggregate } from '../lib/aggregate.ts';

const live = pollImpact();
assert.ok(live);
assert.deepEqual(live.after, currentAggregate);
assert.equal(live.before.date, live.after.date);
assert.ok(live.added.every(p => p.published === live.published));
assert.ok(live.added.every(p => !live.before.pollIds.includes(p.id)));
assert.equal(live.beforeSeats.rows.reduce((s,r) => s+r.seats,0),150);
assert.equal(live.afterSeats.rows.reduce((s,r) => s+r.seats,0),150);
assert.equal(live.rows.reduce((s,r) => s+r.seatDelta,0),0);
assert.ok(live.rows.every(r => r.delta === null || r.delta === Math.round((r.to-r.from)*10)/10));
const template = archive[0];
const make = (id,agency,end,published,values={ps:30,smer:20}) => ({...template,id,agency,end,start:end,published,values});
const fixtures = [make('old','NMS','2026-09-01','2026-09-03'),make('new','NMS','2026-10-01','2026-10-05',{ps:20,smer:30}),make('ako','AKO','2026-09-30','2026-10-03')];
const comparison = pollImpact(fixtures,'2026-10-01');
assert.ok(comparison.before.pollIds.includes('old'));
assert.ok(comparison.before.pollIds.includes('ako'));
assert.ok(comparison.after.pollIds.includes('new'));
assert.ok(!comparison.after.pollIds.includes('old'));
assert.deepEqual(pollImpact([...fixtures].reverse(),'2026-10-01'),comparison);
const tied = pollImpact([...fixtures,make('focus','FOCUS','2026-09-28','2026-10-05')],'2026-10-01');
assert.deepEqual(tied.added.map(p=>p.id).sort(),['focus','new']);
assert.equal(tied.before.pollIds.includes('focus'),false);
assert.equal(pollImpact([make('unknown','NMS','2026-10-01',null)],'2026-10-01'),null);
assert.equal(pollImpact([], '2026-10-01'),null);
assert.equal(pollImpact([make('sanep','SANEP','2026-10-01','2026-10-05')],'2026-10-01'),null);
const expired = pollImpact([make('expired','NMS','2026-07-01','2026-07-03'),fixtures[1]],'2026-10-01');
assert.equal(expired.before.pollIds.length,0);
assert.ok(expired.rows.every(r=>r.from===null&&r.delta===null));
const latePublication = pollImpact([fixtures[1],make('late','AKO','2026-09-20','2026-10-06')],'2026-10-01');
assert.equal(latePublication.added[0].id,'late');
const readings = agencyComparison('ps',fixtures,'2026-10-01');
assert.ok(readings.readings.every(r=>r.value>=readings.min&&r.value<=readings.max));
assert.ok(readings.model.value>=readings.min&&readings.model.value<=readings.max);
assert.equal(agencyComparison('dem',fixtures,'2026-10-01').model,null);
assert.ok(agencyComparison('dem',fixtures,'2026-10-01').readings.every(r=>r.value===null));
assert.equal(agencyComparison('ps',[], '2026-10-01').readings.length,0);
assert.ok(agencyComparison('ps', [make('zero','AKO','2026-10-01','2026-10-02',{ps:0})], '2026-10-01').readings[0].value===0);
console.log('PASS poll impact: same-date control, fallback/expiry, publication ties, missing values, 150 seats, determinism and agency axis.');
